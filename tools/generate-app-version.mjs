import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { format, resolveConfig } from 'prettier';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const prettierConfig = (await resolveConfig(resolve(root, 'package.json'))) ?? {};
const packageJson = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));
const version = String(packageJson.version ?? '').trim();

if (!version) throw new Error('package.json must contain a non-empty version.');

const target = resolve(root, 'src/app/core/update/app-build.generated.ts');
const escapedVersion = version.replaceAll('\\', '\\\\').replaceAll("'", "\\'");
const source = `// Generated by tools/generate-app-version.mjs. Do not edit manually.\nexport const APP_VERSION = '${escapedVersion}';\n`;
await writeFile(target, await format(source, { ...prettierConfig, filepath: target }), 'utf8');

const serviceWorkerConfig = JSON.parse(await readFile(resolve(root, 'ngsw-config.json'), 'utf8'));
serviceWorkerConfig.appData = { ...serviceWorkerConfig.appData, version };
await writeFile(
  resolve(root, 'ngsw-config.generated.json'),
  await format(JSON.stringify(serviceWorkerConfig), {
    ...prettierConfig,
    filepath: resolve(root, 'ngsw-config.generated.json'),
  }),
  'utf8',
);
